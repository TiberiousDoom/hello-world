def place(canvas,glyph,x0,y0):
    for r,row in enumerate(glyph):
        for c,ch in enumerate(row):
            if ch=='#': canvas[y0+r][x0+c]=1
def wordmark(games=True):
    H=15+(5+7 if games else 0); W=11+3+11+3+11+7+11+3+11
    cv=[[0]*W for _ in range(H)]
    x0=0; place(cv,B,x0,0); x0+=14; place(cv,o,x0,5); x0+=14; place(cv,x,x0,5); x0+=11+7
    place(cv,F,x0,0); x0+=14; place(cv,S,x0,0)
    if games:
        letters=['G','A','M','E','S']; widths=[len(G7[l][0]) for l in letters]
        gap=(W-sum(widths))/(len(letters)-1); xx=0.0
        for l,wd in zip(letters,widths):
            place(cv,G7[l],round(xx),20); xx+=wd+gap
    return np.array(cv,bool)
def render(mask,scale=1,bg=None):
    h,w=mask.shape
    img=np.zeros((h,w,4),np.uint8)
    if bg: img[:,:,:3]=bg; img[:,:,3]=255
    img[mask,:3]=INK; img[mask,3]=255
    return Image.fromarray(img,'RGBA').resize((w*scale,h*scale),Image.NEAREST)
